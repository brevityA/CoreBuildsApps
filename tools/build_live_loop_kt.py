#!/usr/bin/env python3
"""Write LiveLoop.kt's LOOPS list from tools/live_roster.py.

The icon pack hard-codes its loop list in Kotlin (no network needed to show
the grid). This keeps that list the roster's, entry for entry, between the
`// LOOPS-BEGIN` and `// LOOPS-END` markers.

    python tools/build_live_loop_kt.py          # rewrite
    python tools/build_live_loop_kt.py --check  # exit 1 if it would change
"""
from __future__ import annotations

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from live_roster import CINEMA, DEEP_SPACE, ICON_ECHO, MOTION, ROOT, ROSTER  # noqa: E402

KT = ROOT / "app" / "src" / "main" / "java" / "tv" / "corebuilds" / "iconpack" / "LiveLoop.kt"
CONST = {"Motion": "MOTION_SERIES", "Deep Space": "DEEP_SPACE_SERIES",
         "Cinema": "CINEMA_SERIES", "Icon Echo": "ICON_ECHO_SERIES"}
WORDS = {6: "six", 12: "twelve", 18: "eighteen", 24: "twenty-four", 30: "thirty",
         36: "thirty-six", 42: "forty-two", 48: "forty-eight"}


def render() -> str:
    entries = []
    for c in ROSTER:
        entries.append(f'''        Loop(
            id = "{c.id}",
            title = "{c.title}",
            fileName = "{c.stem}.mp4",
            revision = "{c.revision}",
            url = RAW_BASE + "{c.stem}.mp4",
            thumbUrl = RAW_BASE + "thumbs/{c.stem}.jpg",
            thumbAsset = "$THUMB_DIR/{c.stem}.jpg",
            stillSeries = {CONST[c.set_name]}
        )''')
    total = WORDS.get(len(ROSTER), str(len(ROSTER)))
    doc = f'''    /**
     * The {WORDS[len(MOTION)]} Motion loops, the {WORDS[len(DEEP_SPACE)]} Deep Space loops, the
     * {WORDS[len(CINEMA)]} Cinema loops and the {WORDS[len(ICON_ECHO)]} Icon Echo loops, each in wall
     * order - {total}, the order the Live chip shows. Generated from
     * tools/live_roster.py by tools/build_live_loop_kt.py; edit the roster,
     * not this list.
     *
     * The first entry is the default: [Prefs.liveLoopId] falls back to it, and
     * so does the engine when it reads a value it does not recognise, so a
     * preference written by a newer build can never leave the home screen
     * blank.
     */
    val MOTION_LOOPS: List<Loop> = listOf(
'''
    return doc + ",\n".join(entries) + "\n    )\n"


def main(argv=None) -> int:
    check = "--check" in (argv or sys.argv[1:])
    src = KT.read_text(encoding="utf-8")
    begin = "    // LOOPS-BEGIN (generated by tools/build_live_loop_kt.py)\n"
    end = "    // LOOPS-END\n"
    i, j = src.find(begin), src.find(end)
    if i < 0 or j < 0:
        print("LiveLoop.kt: LOOPS-BEGIN/LOOPS-END markers not found")
        return 1
    new = src[:i + len(begin)] + render() + src[j:]
    if new == src:
        print(f"LiveLoop.kt in sync ({len(ROSTER)} loops)")
        return 0
    if check:
        print("LiveLoop.kt is stale: run tools/build_live_loop_kt.py")
        return 1
    KT.write_text(new, encoding="utf-8")
    print(f"wrote LiveLoop.kt ({len(ROSTER)} loops)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
