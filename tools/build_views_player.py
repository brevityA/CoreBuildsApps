ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "views-storyboards" / "player.html"
SAMPLE_HZ = 4          # display sampling; the render is 30 fps, this is a card


def view_payload(view: dict) -> dict | None:
    """One view as the page needs it: parameters, samples, captions."""
    if view["lane"] != "render":
        return None
    camera = view.get("camera") or {}
    move = camera.get("move")
    if move not in views_geo.MOVES or not camera.get("startHeightM"):
        return None

    fps = camera.get("fps") or 30
    start = float(camera["startHeightM"])
    end = float(camera.get("endHeightM") or start)
    pitch = float(camera.get("pitch") or renderer.DEFAULT_PITCH.get(move, 55))
    duration = float(view["durationSeconds"])

    step = 1.0 / SAMPLE_HZ
    samples = []
    t = 0.0
    # Bearing is stored *unwrapped*: a ridge-follow oscillating either side of
    # north would otherwise draw a chart that slams between 0 and 360. The page
    # takes the modulo when it needs a heading.
    unwrapped = 0.0
    previous = None
    while t <= duration + 1e-9:
        cam = views_geo.camera_at(view, move, t, duration, start, end, pitch)
        bearing = cam["bearing"]
        if previous is not None:
            delta = ((bearing - previous + 540.0) % 360.0) - 180.0
            unwrapped += delta
        else:
            unwrapped = bearing
        previous = bearing
        samples.append([
            round(t, 2),
            round(cam["center"][0], 5), round(cam["center"][1], 5),
            round(cam["zoom"], 2), round(cam["altitudeM"], 1),
            round(unwrapped, 1), round(cam["pitch"], 1),
        ])
        t += step

    return {
        "id": view["id"],
        "n": view["number"],
        "title": view["title"],
        "place": view["place"],
        "region": view["region"],
        "time": view["timeOfDay"],
        "scene": view["scene"],
        "lane": view["lane"],
        "move": move,
        "fps": fps,
        "duration": duration,
        "captions": [[c["at"], c["text"]] for c in view.get("captions", [])],
        "credits": [c.get("source", "") for c in view.get("credits", [])],
        "samples": samples,
    }


def skipped_note(views: list[dict]) -> list[dict]:
    return [{"n": v["number"], "title": v["title"], "lane": v["lane"]}
            for v in views if v["lane"] != "render"]


def build(catalog: dict | None = None) -> str:
    catalog = catalog or feeds.load_catalog()
    views = feeds.validate(catalog)
    payload = [p for p in (view_payload(v) for v in views) if p]
    payload.sort(key=lambda p: p["n"])
    skipped = skipped_note(views)

    data = json.dumps({"views": payload, "skipped": skipped},
                      ensure_ascii=False, separators=(",", ":"))
    return TEMPLATE.replace("/*__DATA__*/null", data)


