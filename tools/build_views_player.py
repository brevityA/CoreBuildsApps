def write(target: Path = TARGET) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build(), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed player differs from the catalogue")
    parser.add_argument("--out", type=Path, default=TARGET)
    args = parser.parse_args(argv)

    rendered = build()
    if args.check:
        if not args.out.exists():
            print(f"error: {args.out} is missing — run tools/build_views_player.py",
                  file=sys.stderr)
            return 1
        if args.out.read_text(encoding="utf-8") != rendered:
            print(f"error: {args.out} is out of date with views/catalog.json — "
                  "run tools/build_views_player.py", file=sys.stderr)
            return 1
        print(f"ok: {args.out.name} in sync")
        return 0

    write(args.out)
    print(f"wrote {args.out} ({args.out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
