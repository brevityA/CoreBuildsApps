#!/usr/bin/env python3
"""Build a single-file HTML player for Core Views shot cards.

Why this exists
---------------
The shot cards are SVGs: accurate, but static, and a camera move is a thing
that happens over time. This writes one self-contained `.html` — no build, no
bundles, no network at read time — that plays every renderable view's camera
path: the track from above, altitude / bearing / pitch over time, and the
captions landing where they land.

Two rules it keeps:

1. **No invented footage.** There is no imagery in it. It draws the camera, the
   track and the numbers, and says so on the page. A pretty fake aerial of a
   real island is the one thing this project must not produce.
2. **No second copy of the maths.** The samples are generated here from
   `views_geo.camera_path`, the same function the renderer flies. The page only
   interpolates between samples it was handed.

    python tools/build_views_player.py            # write the player
    python tools/build_views_player.py --check    # CI: committed page current
"""

