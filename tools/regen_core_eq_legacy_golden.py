#!/usr/bin/env python3
"""Regenerate (or check) Core EQ's 1.13.2 reference values from the commit itself.

`coreeq/app/src/test/kotlin/tv/corebuilds/eq/LegacyGolden113.kt` holds values that
`LegacySoundCompatibilityTest` compares the current code against: the limiters,
band gains and stored profiles that Core EQ 1.13.2 produced. They must come from
the 1.13.2 code, not from the code under test. This script makes that
reproducible by anyone with the Android SDK.

1. Adds a temporary detached git worktree at the base commit (default 19b8834f,
   `main` when Core EQ 1.13.2 shipped) and verifies the commit hash.
2. Copies in two test sources and nothing else:
   - `LegacyGoldenFixtures.kt` (the inputs, from this checkout);
   - `tools/core_eq_legacy_golden/LegacyGoldenCaptureTest.kt` (the capture).
   The base code itself is left untouched.
3. Runs that one test with the worktree's own Gradle wrapper, which writes
   `coreeq/app/build/legacy-golden.txt`.
4. Renders `LegacyGolden113.kt` from that record, deterministically.
5. With `--check`, compares the rendering with the committed file and exits 1 on
   any difference. Without it, writes the file.
6. Removes the worktree, unless `--keep-worktree` is given.

Usage (from the repository root, ANDROID_HOME or ANDROID_SDK_ROOT set):

    python3 tools/regen_core_eq_legacy_golden.py --check
    python3 tools/regen_core_eq_legacy_golden.py          # rewrite the file

It needs the network only for whatever Gradle and Robolectric would fetch for the
base build. It is not a CI gate: it builds a second copy of the app, so it runs
on demand, when the fixtures or the capture change.
"""
from __future__ import annotations

import argparse
import difflib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE_DEFAULT = "19b8834f020f004dd345127458dc3a2aa9a5cac8"
TEST_PKG = Path("coreeq/app/src/test/kotlin/tv/corebuilds/eq")
FIXTURES = TEST_PKG / "LegacyGoldenFixtures.kt"
CAPTURE = Path("tools/core_eq_legacy_golden/LegacyGoldenCaptureTest.kt")
GOLDEN = TEST_PKG / "LegacyGolden113.kt"
RECORD = Path("coreeq/app/build/legacy-golden.txt")


def run(cmd: list[str], cwd: Path, env: dict[str, str] | None = None) -> None:
    print("+", " ".join(cmd), f"(in {cwd})", flush=True)
    subprocess.run(cmd, cwd=cwd, env=env, check=True)


def kotlin_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def render(record: str, base: str) -> str:
    """The committed Kotlin, from the capture's text record. Pure and deterministic."""
    limiters, dp, eq, loaded, loaded_manual = [], [], [], [], []
    js = None
    for line in record.splitlines():
        if line.startswith("LIMITER "):
            parts = line.split()
            limiters.append((parts[1].split("=")[1], parts[2:]))
        elif line.startswith("DP "):
            _, pid, case, side, rest = line.split(" ", 4)
            dp.append((pid, case, side, rest))
        elif line.startswith("EQ "):
            _, pid, case, head, rest = line.split(" ", 4)
            eq.append((pid, case, head, rest))
        elif line.startswith("LOADED "):
            _, pid, case, side, rest = line.split(" ", 4)
            loaded.append((pid, case, side, rest))
        elif line.startswith("LOADEDMANUAL "):
            parts = line.split(" ", 2)
            loaded_manual.append((parts[1], parts[2] if len(parts) > 2 else ""))
        elif line.startswith("JSON "):
            js = line[5:]
    if len(limiters) != 2 or not dp or not eq or not loaded or js is None:
        raise SystemExit("capture record is incomplete; see the Gradle output above")

    o = [
        "package tv.corebuilds.eq",
        "",
        "import tv.corebuilds.eq.apply.LimiterSettings",
        "",
        "/**",
        f" * Values computed by Core EQ 1.13.2 itself (commit {base[:8]}, `main` before the",
        " * listening batch) from [LegacyGoldenFixtures]. Generated by",
        " * `tools/regen_core_eq_legacy_golden.py`, which runs",
        " * `tools/core_eq_legacy_golden/LegacyGoldenCaptureTest.kt` in a worktree of that",
        " * commit; `--check` regenerates and compares. Do not edit by hand. Configured",
        " * gains and limiter parameters only: nothing here was played or heard.",
        " */",
        "object LegacyGolden113 {",
        "",
    ]
    for night, v in limiters:
        en, lk, att, rel, ratio, thr, knee, post = v
        name = "NIGHT_ON_LIMITER" if night == "true" else "PROTECTION_LIMITER"
        o.append(
            f"    val {name} = LimiterSettings(enabled = {en}, linked = {lk}, attackMs = {att}f, "
            f"releaseMs = {rel}f, ratio = {ratio}f, thresholdDb = {thr}f, kneeWidthDb = {knee}f, postGainDb = {post}f)"
        )
    o += ["", '    /** DynamicsProcessing bands for each fixture as built, keyed "profileId|case|side". */',
          "    val DP: Map<String, DoubleArray> = mapOf("]
    o.append(",\n".join(f'        "{a}|{b}|{c}" to {r}' for a, b, c, r in dp))
    o.append("    )")
    o += ["", '    /** Five-band Equalizer fit, keyed "profileId|case": headroom and configured bands. */',
          "    val EQ: Map<String, Pair<Double, DoubleArray>> = mapOf("]
    o.append(",\n".join(f'        "{a}|{b}" to ({h} to {r})' for a, b, h, r in eq))
    o.append("    )")
    o += ["", "    /** The three fixtures as 1.13.2 stored them (`profiles_json`). */",
          "    const val PROFILES_JSON: String = " + kotlin_string(js)]
    o += ["", "    /**",
          "     * The same JSON loaded by 1.13.2: ProfileStore moves legacy manual bands into",
          "     * the Everyday overlay; these are the Everyday effective profile's bands,",
          '     * keyed "profileId|case|side", and its manual filters as "fc,q,gain;…".',
          "     */",
          "    val LOADED: Map<String, DoubleArray> = mapOf("]
    o.append(",\n".join(f'        "{a}|{b}|{c}" to {r}' for a, b, c, r in loaded))
    o.append("    )")
    o.append("    val LOADED_MANUAL: Map<String, String> = mapOf(")
    o.append(",\n".join(f'        "{a}" to "{m}"' for a, m in loaded_manual))
    o.append("    )")
    o.append("}")
    return "\n".join(o) + "\n"


def capture(base: str, keep: bool) -> str:
    sdk = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
    if not sdk:
        raise SystemExit("set ANDROID_HOME (or ANDROID_SDK_ROOT) to an Android SDK")
    tmp = Path(tempfile.mkdtemp(prefix="coreeq-legacy-golden-"))
    tree = tmp / "base"
    run(["git", "worktree", "add", "--quiet", "--detach", str(tree), base], ROOT)
    try:
        resolved = subprocess.run(["git", "rev-parse", "HEAD"], cwd=tree, check=True,
                                  capture_output=True, text=True).stdout.strip()
        if not resolved.startswith(base) and resolved != base:
            raise SystemExit(f"worktree is at {resolved}, not {base}")
        for src in (FIXTURES, CAPTURE):
            dest = tree / TEST_PKG / src.name
            if dest.exists():
                raise SystemExit(f"{dest} already exists at {base}; refusing to overwrite base code")
            shutil.copyfile(ROOT / src, dest)
        env = dict(os.environ, ANDROID_HOME=sdk)
        run(["./gradlew", "-q", ":app:testDebugUnitTest", "--tests", "tv.corebuilds.eq.LegacyGoldenCaptureTest"],
            tree / "coreeq", env)
        return (tree / RECORD).read_text(encoding="utf-8")
    finally:
        if keep:
            print(f"worktree kept at {tree}")
        else:
            subprocess.run(["git", "worktree", "remove", "--force", str(tree)], cwd=ROOT, check=False)
            shutil.rmtree(tmp, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--base", default=BASE_DEFAULT, help="commit to capture from (default: 1.13.2 main)")
    ap.add_argument("--check", action="store_true", help="compare with the committed file; exit 1 on difference")
    ap.add_argument("--keep-worktree", action="store_true", help="leave the temporary worktree for inspection")
    ap.add_argument("--record", type=Path, help="render from an existing capture record instead of running Gradle")
    args = ap.parse_args()

    record = args.record.read_text(encoding="utf-8") if args.record else capture(args.base, args.keep_worktree)
    rendered = render(record, args.base)
    target = ROOT / GOLDEN
    if args.check:
        committed = target.read_text(encoding="utf-8")
        if committed == rendered:
            print(f"legacy golden ok - {GOLDEN} matches a fresh capture from {args.base[:8]}")
            return 0
        diff = difflib.unified_diff(committed.splitlines(), rendered.splitlines(), "committed", "regenerated", lineterm="", n=1)
        print("\n".join(list(diff)[:40]))
        print(f"legacy golden DIFFERS from a fresh capture at {args.base[:8]}")
        return 1
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {GOLDEN} from {args.base[:8]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
