BUTTON_DRAWABLE = {"cta": "bg_cta", "ghost": "bg_ghost", "chip": "bg_chip_toggle",
                   "toggle": "bg_chip_toggle"}
BUTTON_INK = {"cta": "cb_cta_ink", "ghost": "cb_ink", "chip": "cb_ink",
              "toggle": "cb_ink"}
BUTTON_SIZE = {"cta": "cb_text_body", "ghost": "cb_text_body",
               "chip": "cb_text_label", "toggle": "cb_text_data"}


def _button_xml(e: Emitter, btn: dict, links: dict, tag: str = "TextView") -> None:
    style = btn.get("style", "ghost")
    e.open(f"<{tag}")
    e.line(f'android:id="@+id/{btn["id"]}"')
    e.line('android:layout_width="wrap_content"')
    e.line('android:layout_height="wrap_content"')
    if btn.get("_marginStart"):
        e.line('android:layout_marginStart="@dimen/cb_space_sm"')
    e.line('android:minHeight="@dimen/cb_target_min"')
    e.line('android:gravity="center"')
    e.line(f'android:background="@drawable/{BUTTON_DRAWABLE[style]}"')
    e.line('android:clickable="true"')
    e.line('android:focusable="true"')
    e.line('android:focusableInTouchMode="true"')
    for attr in link_attrs(btn["id"], links):
        e.line(attr)
    e.line('android:paddingStart="@dimen/cb_space_md"')
    e.line('android:paddingEnd="@dimen/cb_space_md"')
    e.line('android:paddingTop="@dimen/cb_space_sm"')
    e.line('android:paddingBottom="@dimen/cb_space_sm"')
    e.line(f'android:text="{btn["text"]}"')
    e.line(f'android:textColor="@color/{BUTTON_INK[style]}"')
    e.line(f'android:textSize="@dimen/{btn.get("size", BUTTON_SIZE[style])}"')
    e.line('android:textStyle="bold" />')
    e.depth -= 1


def _recycler_xml(e: Emitter, vid: str, links: dict, horizontal: bool,
                  weight: bool, gone: bool = False,
                  margin_top: str = "cb_space_md") -> None:
    e.open("<androidx.recyclerview.widget.RecyclerView")
    e.line(f'android:id="@+id/{vid}"')
    e.line('android:layout_width="match_parent"')
    if weight:
        e.line('android:layout_height="0dp"')
    else:
        e.line('android:layout_height="wrap_content"')
    e.line(f'android:layout_marginTop="@dimen/{margin_top}"')
    if weight:
        e.line('android:layout_weight="1"')
    e.line('android:clipToPadding="false"')
    if horizontal:
        e.line('android:orientation="horizontal"')
    if gone:
        e.line('android:visibility="gone"')
    for attr in link_attrs(vid, links):
        e.line(attr)
    e.line("/>")
    e.depth -= 1


def render_layout(spec: Spec, links: dict[str, dict[str, str]]) -> str:
    e = Emitter()
    e.line('<?xml version="1.0" encoding="utf-8"?>')
    e.line(f"<!-- Generated by tools/build_ui.py for {spec.activity}.")
    e.line("     D-pad wiring is explicit nextFocus* throughout; the audit is")
    e.line("     `python tools/validate_ui.py <this file>`. Safe to restyle,")
    e.line("     keep the ids (generated Kotlin points at them). -->")
    e.open("<LinearLayout")
    e.line('xmlns:android="http://schemas.android.com/apk/res/android"')
    e.line(f'android:id="@+id/{spec.prefix}_root"')
    e.line('android:layout_width="match_parent"')
    e.line('android:layout_height="match_parent"')
    e.line('android:orientation="vertical"')
    e.line('android:background="@color/cb_night"')
    e.line('android:paddingStart="@dimen/cb_gutter_side"')
    e.line('android:paddingEnd="@dimen/cb_gutter_side"')
    e.line('android:paddingTop="@dimen/cb_gutter_top"')
    e.line('android:paddingBottom="@dimen/cb_gutter_bottom">')
    for block in spec.blocks:
        _render_block(e, spec, block, links)
    e.close("</LinearLayout>")
    return e.text()


def _render_block(e: Emitter, spec: Spec, block: dict,
                  links: dict[str, dict[str, str]]) -> None:
    t = block["type"]
    render = {
        "header": _block_header, "actions": _block_actions,
        "targets": _block_targets, "updatebar": _block_updatebar,
        "chips": _block_chips, "search": _block_search,
        "filterrow": _block_filterrow, "grid": _block_grid,
        "hero": _block_hero, "settings": _block_settings,
        "empty": _block_empty, "selectionbar": _block_selectionbar,
        "hint": _block_hint,
    }[t]
    e.line()
    render(e, spec, block, links)


