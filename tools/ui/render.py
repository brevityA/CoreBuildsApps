def _activity_block(e: Emitter, spec: Spec, block: dict, links: dict, ctx: dict) -> None:
    t = block["type"]
    if t == "header":
        for btn in block.get("side") or []:
            _activity_button(e, btn)
    elif t == "actions":
        for btn in block.get("buttons") or []:
            _activity_button(e, btn)
    elif t == "settings":
        for row in block.get("rows") or []:
            _activity_button(e, {"id": row["id"], "text": row["label"],
                                 **({"go": row["go"]} if "go" in row else {})})
    elif t == "targets":
        vid = block["id"]
        e.line(f"        findViewById<RecyclerView>(R.id.{vid}).apply {{")
        e.line("            layoutManager = LinearLayoutManager(")
        e.line(f"                this@{spec.activity}, LinearLayoutManager.HORIZONTAL, false)")
        e.line("            // TODO: attach a ChipAdapter when targets exist, then")
        e.line("            // DpadNav.chainVertical(...) through this row and show it.")
        e.line("        }")
        e.line()
    elif t == "updatebar":
        bid = block["button_id"]
        e.line(f"        TvFocus.attach(findViewById(R.id.{bid}))")
        e.line(f"        findViewById<TextView>(R.id.{bid}).setOnClickListener {{")
        e.line("            // TODO: update action.")
        e.line(f"            set{IDDENorm(block['id'])}Visible(false)")
        e.line("        }")
        e.line()
    elif t in ("chips", "filterrow"):
        _activity_chips(e, spec, block, ctx)
        if t == "filterrow" and ctx["filterable"]:
            _activity_search(e, spec, block["search_id"], ctx)
    elif t == "search" and ctx["filterable"]:
        _activity_search(e, spec, block["id"], ctx)
    elif t == "search":
        e.line(f"        // Search field: R.id.{block['id']}. TODO: wire a TextWatcher.")
        e.line()
    elif t == "grid":
        _activity_grid(e, spec, block, links, ctx)
    elif t == "empty":
        e.line(f"        TvFocus.attach(findViewById(R.id.{block['primary_id']}))")
        e.line(f"        TvFocus.attach(findViewById(R.id.{block['secondary_id']}))")
        if ctx["filterable"]:
            if ctx["search_id"]:
                e.line(f"        findViewById<TextView>(R.id.{block['primary_id']})"
                       ".setOnClickListener {")
                e.line(f"            findViewById<EditText>(R.id.{ctx['search_id']})"
                       '.setText("")')
                e.line("        }")
            e.line(f"        findViewById<TextView>(R.id.{block['secondary_id']})"
                   ".setOnClickListener {")
            if ctx["chips_id"]:
                e.line('            chipAdapter.select("ALL")')
            e.line("        }")
        else:
            e.line(f"        // Empty-state buttons: R.id.{block['primary_id']},")
            e.line(f"        // R.id.{block['secondary_id']}. TODO: wire undo actions.")
        e.line()
    elif t == "selectionbar":
        for b in block.get("buttons") or []:
            e.line(f"        TvFocus.attach(findViewById(R.id.{b['id']}))")
        e.line("        // TODO: wire selection actions, then set...Visible(false).")
        e.line()
    elif t == "hero":
        e.line("        // TODO: bind hero art/title to the selected item.")
        e.line()


