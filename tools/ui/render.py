def render_strings(spec: Spec) -> str:
    strings = dict(spec.extra_strings)
    strings.update(spec.extracted)
    e = Emitter()
    e.line('<?xml version="1.0" encoding="utf-8"?>')
    e.line(f"<!-- Generated by tools/build_ui.py for {spec.activity}. -->")
    e.line("<!-- --apply merges these into values/strings.xml (skipping names")
    e.line("     that already exist); Pop inherits them via the string mirror. -->")
    e.line("<resources>")
    for name in sorted(strings):
        e.line(f"    <string name=\"{name}\">{esc(strings[name])}</string>")
    e.line("</resources>")
    e.line()
    return e.text()


def manifest_entry(spec: Spec) -> str:
    header = _blocks_of(spec, "header")[0]
    label = header["title"]
    label_ref = label if label.startswith("@") else "@string/app_name"
    return (
        "        <activity\n"
        f'            android:name=".{spec.activity}"\n'
        '            android:exported="false"\n'
        f'            android:label="{label_ref}"\n'
        '            android:theme="@style/Theme.CoreBuilds" />\n'
    )

