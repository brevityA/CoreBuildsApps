def _search_xml(e: Emitter, vid: str, links: dict, width: str,
                margin_top: str, hint: str,
                margin_start: str | None = None) -> None:
    e.open('<EditText')
    e.line(f'android:id="@+id/{vid}"')
    e.line(f'android:layout_width="{width}"')
    e.line('android:layout_height="wrap_content"')
    e.line('android:minHeight="@dimen/cb_target_min"')
    if margin_top:
        e.line(f'android:layout_marginTop="@dimen/{margin_top}"')
    if margin_start:
        e.line(f'android:layout_marginStart="@dimen/{margin_start}"')
    e.line('android:background="@drawable/bg_search"')
    e.line('android:focusable="true"')
    e.line('android:focusableInTouchMode="true"')
    for attr in link_attrs(vid, links):
        e.line(attr)
    e.line(f'android:hint="{hint}"')
    e.line('android:imeOptions="actionSearch"')
    e.line('android:importantForAutofill="no"')
    e.line('android:inputType="text"')
    e.line('android:paddingStart="@dimen/cb_space_md"')
    e.line('android:paddingEnd="@dimen/cb_space_md"')
    e.line('android:paddingTop="@dimen/cb_space_sm"')
    e.line('android:paddingBottom="@dimen/cb_space_sm"')
    e.line('android:textColor="@color/cb_ink"')
    e.line('android:textColorHint="@color/cb_slate"')
    e.line('android:textSize="@dimen/cb_text_label" />')
    e.depth -= 1


