"""Renderers: spec -> layout XML, Kotlin, strings, manifest snippet.

The D-pad wiring is computed up front (compute_links) and baked into the
layout as explicit nextFocus* attributes, so generated screens navigate
deterministically on any panel instead of relying on spatial focus search.
"""
from __future__ import annotations

from xml.sax.saxutils import escape as _escape

from .spec import Spec, compute_links, default_initial_focus, focus_levels

DIR_ATTR = {"up": "Up", "down": "Down", "left": "Left", "right": "Right"}

__all__ = ["compute_links", "default_initial_focus", "focus_levels"]


def esc(text: str) -> str:
    return _escape(text, {'"': "&quot;", "'": "&apos;"})


def kt_str(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


class Emitter:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.depth = 0

    def line(self, text: str = "") -> None:
        self.lines.append("    " * self.depth + text if text else "")

    def open(self, text: str) -> None:
        self.line(text)
        self.depth += 1

    def close(self, text: str) -> None:
        self.depth -= 1
        self.line(text)

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


# --------------------------------------------------------------------------
# D-pad wiring is computed in spec.py (focus_levels / compute_links) so the
# validator, the CLI and Studio share one model. This module renders it.
# --------------------------------------------------------------------------

def link_attrs(vid: str, links: dict[str, dict[str, str]]) -> list[str]:
    return [
        f'android:nextFocus{DIR_ATTR[d]}="@id/{t}"'
        for d, t in sorted((links.get(vid) or {}).items())
    ]


