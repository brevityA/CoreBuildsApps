def render_adapter(spec: Spec) -> str:
    """A working starter adapter: stable ids + DiffUtil + focus zoom."""
    p = spec.prefix
    return f"""package {spec.package}

import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.ImageView
import android.widget.TextView
import androidx.recyclerview.widget.DiffUtil
import androidx.recyclerview.widget.RecyclerView
import {spec.package}.ui.TvFocus

/**
 * Generated by tools/build_ui.py for {spec.activity}.
 *
 * Stable ids + DiffUtil: filtering never drops the D-pad highlight, and item
 * animations survive data changes. Focus zoom is attached here (not in the
 * Activity) so it applies per view-holder.
 *
 * TODO: replace [sampleRows] with your data source.
 */
class {spec.screen}Adapter(
    private var items: List<Row>,
    private val onActivate: (Row) -> Unit
) : RecyclerView.Adapter<{spec.screen}Adapter.VH>() {{

    data class Row(
        val key: String,
        val title: String,
        val sub: String,
        /** Drawable name resolved at bind time; blank leaves the art empty. */
        val drawable: String = ""
    )

    class VH(view: View) : RecyclerView.ViewHolder(view) {{
        val image: ImageView = view.findViewById(R.id.{p}_item_image)
        val title: TextView = view.findViewById(R.id.{p}_item_title)
        val sub: TextView = view.findViewById(R.id.{p}_item_sub)
    }}

    init {{
        setHasStableIds(true)
    }}

    override fun getItemId(position: Int): Long = items[position].key.hashCode().toLong()

    override fun onCreateViewHolder(parent: ViewGroup, viewType: Int): VH {{
        val v = LayoutInflater.from(parent.context)
            .inflate(R.layout.item_{p}, parent, false)
        TvFocus.attach(v)
        return VH(v)
    }}

    override fun onBindViewHolder(holder: VH, position: Int) {{
        val item = items[position]
        val ctx = holder.image.context
        if (item.drawable.isNotEmpty()) {{
            val id = ctx.resources.getIdentifier(item.drawable, "drawable", ctx.packageName)
            if (id != 0) holder.image.setImageResource(id)
        }}
        holder.title.text = item.title
        holder.sub.text = item.sub
        holder.itemView.contentDescription = item.title
        holder.itemView.setOnClickListener {{ onActivate(item) }}
    }}

    override fun getItemCount() = items.size

    fun submit(next: List<Row>) {{
        val previous = items
        val result = DiffUtil.calculateDiff(object : DiffUtil.Callback() {{
            override fun getOldListSize() = previous.size
            override fun getNewListSize() = next.size
            override fun areItemsTheSame(old: Int, new: Int) =
                previous[old].key == next[new].key
            override fun areContentsTheSame(old: Int, new: Int) =
                previous[old] == next[new]
        }})
        items = next
        result.dispatchUpdatesTo(this)
    }}

    companion object {{
        /** Placeholder rows so the generated screen runs before data lands. */
        fun sampleRows(): List<Row> = listOf(
            Row("row_1", "First row", "subtitle", "cb_banner"),
            Row("row_2", "Second row", "subtitle", "cb_banner"),
            Row("row_3", "Third row", "subtitle", "cb_banner")
        )
    }}
}}
"""


