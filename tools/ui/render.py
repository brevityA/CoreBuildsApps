def _blocks_of(spec: Spec, *types: str) -> list[dict]:
    return [b for b in spec.blocks if b["type"] in types]


def render_activity(spec: Spec, links: dict[str, dict[str, str]]) -> str:
    grids = _blocks_of(spec, "grid")
    chips_blocks = _blocks_of(spec, "chips", "filterrow")
    searches = _blocks_of(spec, "search", "filterrow")
    has_chips = bool(chips_blocks)
    has_search = bool(searches)
    grid = grids[0] if grids else None
    source = grid["source"] if grid else ""
    filterable = grid is not None and source in ("icons", "walls") and (
        has_chips or has_search)
    header = _blocks_of(spec, "header")[0]
    count_id = header.get("count_id") if header.get("showCount", True) else None

    chips_id = chips_keys = None
    if chips_blocks:
        cb = chips_blocks[0]
        chips_id = cb["chips_id"] if cb["type"] == "filterrow" else cb["id"]
        chips_keys = (cb.get("keys") or ["ALL"], cb.get("labels") or ["All"])
    search_id = None
    if searches:
        sb = searches[0]
        search_id = sb["search_id"] if sb["type"] == "filterrow" else sb["id"]

    initial = spec.dpad.get("initialFocus") or _default_initial(spec)
    anim = spec.anim

    imports = [
        "import android.content.Intent",
        "import android.os.Bundle",
        "import android.view.View",
        "import android.widget.TextView",
        "import android.widget.Toast",
        "import androidx.appcompat.app.AppCompatActivity",
    ]
    if grid:
        imports.append("import androidx.recyclerview.widget.GridLayoutManager")
    if chips_blocks or _blocks_of(spec, "targets"):
        imports.append("import androidx.recyclerview.widget.LinearLayoutManager")
    if grids or chips_blocks or _blocks_of(spec, "targets"):
        imports.append("import androidx.recyclerview.widget.RecyclerView")
    if has_search and filterable:
        imports += ["import android.text.Editable",
                    "import android.text.TextWatcher",
                    "import android.widget.EditText"]
    imports += [f"import {spec.package}.ui.DpadNav",
                f"import {spec.package}.ui.TvFocus",
                f"import {spec.package}.ui.focusFirst"]
    has_go = any("go" in b for b in _all_buttons(spec))
    if not has_go:
        imports = [i for i in imports if i != "import android.content.Intent"]

    e = Emitter()
    e.line(f"package {spec.package}")
    e.line()
    for imp in imports:
        e.line(imp)
    e.line()
    e.line("/**")
    e.line(f" * Generated by tools/build_ui.py for R.layout.{spec.layout}.")
    e.line(" *")
    e.line(" * D-pad: every focusable carries explicit nextFocus* (see the layout),")
    e.line(" * the grid escapes its first row upward via DpadNav.installTopEdge, and")
    e.line(" * contextual bars re-chain their neighbours when they toggle.")
    e.line(" * Motion: TvFocus zoom on buttons and grid items, staggered enter.")
    e.line(" * Audit any restyle with `python tools/validate_ui.py <layout>`.")
    e.line(" */")
    e.line(f"class {spec.activity} : AppCompatActivity() {{")
    e.line()
    # fields
    if source == "icons":
        e.line("    private lateinit var allIcons: List<IconAdapter.IconItem>")
        e.line("    private lateinit var gridAdapter: IconAdapter")
        if has_chips:
            e.line('    private var category = "ALL"')
        if has_search:
            e.line('    private var query = ""')
    elif source == "walls":
        e.line("    private lateinit var allWalls: List<Wallpaper>")
        e.line("    private lateinit var gridAdapter: WallpaperAdapter")
        if has_chips:
            e.line('    private var series = "ALL"')
    elif grid:
        e.line(f"    private lateinit var gridAdapter: {spec.screen}Adapter")
    if has_chips:
        e.line("    private lateinit var chipAdapter: ChipAdapter")
    if has_chips or grid or has_search:
        e.line()
    e.line("    override fun onCreate(savedInstanceState: Bundle?) {")
    e.line("        super.onCreate(savedInstanceState)")
    e.line(f"        setContentView(R.layout.{spec.layout})")
    e.line()
    # Data loads before any block binds: catalog chips read the same lists
    # the grid shows, so chips and grid can never disagree.
    if source == "icons":
        e.line("        val drawables = resources.getStringArray(R.array.icon_pack)")
        e.line("        val names = resources.getStringArray(R.array.icon_names)")
        e.line("        val cats = resources.getStringArray(R.array.icon_categories)")
        e.line("        allIcons = drawables.indices.map { i ->")
        e.line("            IconAdapter.IconItem(drawables[i],")
        e.line("                names.getOrElse(i) { drawables[i] },")
