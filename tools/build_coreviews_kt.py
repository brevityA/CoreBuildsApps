#!/usr/bin/env python3
"""Write CoreViewsLoop.kt from tools/coreviews_roster.py.

The icon pack hard-codes its loop list in Kotlin — no network to show the
grid, no parsing to know what the engine can play. The Motion line's list is
generated by `tools/build_live_loop_kt.py`; this is the same contract for the
Core Views season, and `LiveLoop.LOOPS` is the two of them concatenated.

    python tools/build_coreviews_kt.py          # rewrite
    python tools/build_coreviews_kt.py --check  # exit 1 if it would change
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from coreviews_roster import CLIPS  # noqa: E402

KT = (Path(__file__).resolve().parent.parent
      / "app" / "src" / "main" / "java" / "tv" / "corebuilds" / "iconpack")

HEADER = '''package tv.corebuilds.iconpack

/**
 * The Core Views season as live wallpapers: twelve aerial views, each with its
 * own camera move, caption track and credits.
 *
 * Generated from `tools/coreviews_roster.py` (itself read from
 * `views/catalog.json`) by `tools/build_coreviews_kt.py`. Edit the catalogue,
 * not this file.
 *
 * [LiveLoop.LOOPS] is this list appended to the Motion line's, so the engine,
 * the rotation and the browser grid have one list to read. Two things follow
 * from that, and both are deliberate:
 *
 *  - the Motion set comes first, because its first entry is the shipped
 *    default for a preference this build does not recognise;
 *  - a loop here is drawn contour art, `views/catalog.json`'s *plan* of a view
 *    rather than a render of the place. [Loop.fileName] is what a device
 *    caches and plays; when a view's rendered 1080p lands it replaces that
 *    file, and this list does not otherwise change.
 */
object CoreViewsLoop {

    /** The browser chip's key. `series-core-views` label-ises to "Core Views". */
    const val SERIES = "series-core-views"

    /** Bundled poster frames, under assets/. */
    const val THUMB_DIR = "coreviews_thumbs"

    private const val RAW_BASE =
        "https://raw.githubusercontent.com/brevityA/CoreBuildsApps/main/Motion/live/"

    // LOOPS-BEGIN (generated by tools/build_coreviews_kt.py)
'''

FOOTER = '''    )
    // LOOPS-END
}
'''


def render_entries() -> str:
    entries = []
    for c in CLIPS:
        entries.append(f'''        Loop(
            id = "{c.id}",
            title = "{c.title}",
            fileName = "{c.stem}.mp4",
            revision = "{revision(c)}",
            url = RAW_BASE + "{c.stem}.mp4",
            thumbUrl = RAW_BASE + "thumbs/{c.stem}.jpg",
            thumbAsset = "$THUMB_DIR/{c.stem}.jpg",
            stillSeries = ""
        )''')
    return ",\n".join(entries) + "\n"


def revision(clip) -> str:
    """First 12 hex digits of the committed MP4's sha256: [Loop.revision].

    A re-render keeps the file name and the URL (installed builds hard-code
    them), so the content is what tells a device its cached copy is old.
    """
    import hashlib
    if not clip.mp4.is_file():
        raise SystemExit(f"missing {clip.mp4} — run tools/build_coreviews_loops.py")
    return hashlib.sha256(clip.mp4.read_bytes()).hexdigest()[:12]


def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    target = KT / "CoreViewsLoop.kt"
    body = render_entries()
    if target.exists():
        src = target.read_text(encoding="utf-8")
        start = src.find("    // LOOPS-BEGIN")
        end = src.find("    // LOOPS-END")
        if start < 0 or end < 0:
            print("CoreViewsLoop.kt: LOOPS-BEGIN/LOOPS-END markers not found")
            return 1
        head = src[:src.find("\n", start) + 1]
        # Keep the closing paren and the end marker: the list and everything
        # after it are what this script owns.
        tail = src[src.rfind("    )", 0, end):]
        new = head + _doc() + body + tail
    else:
        new = HEADER + _doc() + body + FOOTER

    if target.exists() and new == target.read_text(encoding="utf-8"):
        print(f"CoreViewsLoop.kt in sync ({len(CLIPS)} loops)")
        return 0
    if check:
        print("CoreViewsLoop.kt is stale: run tools/build_coreviews_kt.py")
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(new, encoding="utf-8")
    print(f"wrote CoreViewsLoop.kt ({len(CLIPS)} loops)")
    return 0


def _doc() -> str:
    return """    /**
     * The twelve season-1 views, in catalogue order.
     *
     * [Loop.stillSeries] is empty: these loops are not the moving form of a
     * committed still. Their art is generated from the view's own seed, and
     * their poster frames ship in `coreviews_thumbs/`.
     */
    val LOOPS: List<Loop> = listOf(
"""


if __name__ == "__main__":
    sys.exit(main())
