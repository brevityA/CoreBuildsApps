#!/usr/bin/env python3
"""Coverage and mapping reliability, from the tracker and the shipped pack.

Why this exists
---------------
The feedback loop is the product: users report a missing icon or a mapping
that is not applying, the pack ships the fix, the issue closes. Nobody can
tell how good that loop is until someone cross-checks the tracker against
the shipped appfilter by hand - which is exactly how the first numbers for
2.4.0 were produced (two throwaway scripts and a regex bug). This makes the
cross-check a standing tool:

  * **Icon requests** - how many distinct apps people actually asked for,
    how many are in the pack now, and how fast closed requests were resolved.
  * **Mapping reliability** - of the closed "not applying" reports, how many
    have the *exact reported component* shipped in appfilter now (the
    first-fix rate), how many only the package, and how many nowhere -
    broken down per launcher, because half of "not applying" is the launcher.

The output is a committed Markdown document (docs/COVERAGE.md) refreshed by a
weekly workflow, so the numbers can be cited in issue replies and listings
without re-deriving them.

What is checked where
---------------------
  --write   fetch the tracker via the GitHub API, cross-check appfilter,
            write docs/COVERAGE.md (the scheduled workflow runs this)
  --check   no network: the committed report exists, carries the generator
            header, and is no older than STALE_AFTER_DAYS - the CI gate,
            which cannot fail on tracker churn
  (none)    fetch and print to stdout, for looking

The cross-check is deliberately conservative: a closed request counts as
mapped only when its package (from the component, or from a Play store
link's `id=`) appears in the bundled appfilter. Name matches are reported
separately and never counted, because a label hit is a coin flip.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO_OWNER = "brevityA"
REPO_NAME = "CoreBuildsApps"
APPFILTER = ROOT / "app/src/main/assets/appfilter.xml"
VERSION_JSON = ROOT / "app/src/main/assets/version.json"
REPORT = ROOT / "docs/COVERAGE.md"
HEADER_MARKER = "Generated by tools/coverage_report.py"
# Weekly refresh + slack: the gate fails on a lapsed schedule, not on tracker
# churn between refreshes.
STALE_AFTER_DAYS = 8

GRAPHQL = """
query($after: String) {
  repository(owner: "%(owner)s", name: "%(name)s") {
    issues(first: 100, after: $after, states: [OPEN, CLOSED]) {
      nodes {
        number title body state createdAt closedAt
        labels(first: 5) { nodes { name } }
      }
      pageInfo { hasNextPage endCursor }
    }
  }
}
""" % {"owner": REPO_OWNER, "name": REPO_NAME}


# ---------------------------------------------------------------------------
# The tracker
# ---------------------------------------------------------------------------

def fetch_issues() -> list[dict]:
    """Every issue in the repo, body included, one GraphQL page at a time."""
    issues: list[dict] = []
    after = None
    while True:
        args = ["gh", "api", "graphql", "-f", f"query={GRAPHQL}"]
        if after:
            args += ["-f", f"after={after}"]
        out = subprocess.run(args, capture_output=True, text=True, check=True)
        page = json.loads(out.stdout)["data"]["repository"]["issues"]
        issues.extend(page["nodes"])
        if not page["pageInfo"]["hasNextPage"]:
            return issues
        after = page["pageInfo"]["endCursor"]


def body_field(body: str, heading: str) -> str:
    """The value under a `### heading` in a GitHub form body, trimmed."""
    m = re.search(rf"^###\s+{re.escape(heading)}\s*\n+(.+?)(?=\n###\s|\Z)",
                  body or "", re.M | re.S)
    return m.group(1).strip() if m else ""


def component_of(issue: dict) -> str:
    body = issue.get("body") or ""
    comp = body_field(body, r"component name on YOUR device") \
        or body_field(body, "Component name")
    if re.fullmatch(r"[\w.]+/[\w.]+", comp):
        return comp
    m = re.search(r"\b[\w.]+/[\w.]+\b", body)
    return m.group(0) if m else ""


def package_of(issue: dict) -> str:
    """The app's package: the component's, or a Play store link's `id=`.

    The store link is where the request form points people, and a Play URL
    carries the package in cleartext - so most requests are resolvable to a
    package even when the reporter could not run adb.
    """
    comp = component_of(issue)
    if comp:
        return comp.split("/")[0]
    link = body_field(issue.get("body") or "", "Store or download link")
    m = re.search(r"[?&]id=([\w.]+)", link)
    if m:
        return m.group(1)
    m = re.search(r"\bcom\.[\w.]+", link)
    return m.group(0) if m else ""


def launcher_of(issue: dict) -> str:
    """The launcher a not-applying report came from.

    New reports carry it in the device line too (", Projectivy Launcher");
    the form's own Launcher section is the primary source, that the fallback.
    """
    body = issue.get("body") or ""
    launcher = body_field(body, "Launcher")
    if launcher:
        return launcher
    m = re.search(r",\s*([A-Z][\w ]+?)\s*$", body_field(body, "Device and OS"))
    return m.group(1) if m else "Unstated"


def is_icon_request(issue: dict) -> bool:
    return issue["title"].startswith("[Icon]")


def is_not_applying(issue: dict) -> bool:
    return issue["title"].startswith("[Not applying]")


def app_name_of(issue: dict) -> str:
    """The app a request is about: the title (minus the prefix) first, the
    form's App name field when the title is a bare prefix."""
    name = issue["title"]
    for prefix in ("[Not applying] ", "[Icon] "):
        if name.startswith(prefix):
            name = name[len(prefix):]
            break
    name = name.strip()
    if name:
        return name
    return body_field(issue.get("body") or "", "App name") or f"#{issue['number']}"


def days_between(created: str, closed: str) -> float:
    a = datetime.fromisoformat(created.replace("Z", "+00:00"))
    b = datetime.fromisoformat(closed.replace("Z", "+00:00"))
    return (b - a).total_seconds() / 86400


def median(values: list[float]) -> float:
    if not values:
        return 0.0
    values = sorted(values)
    mid = len(values) // 2
    return values[mid] if len(values) % 2 else (values[mid - 1] + values[mid]) / 2


# ---------------------------------------------------------------------------
# The shipped pack
# ---------------------------------------------------------------------------

def load_pack() -> dict:
    text = APPFILTER.read_text(encoding="utf-8")
    components = set(re.findall(r"ComponentInfo\{([\w.]+)/([\w.]+)\}", text))
    components |= {(p, a) for p, a in re.findall(
        r'(?:name|activity)="([\w.]+)/([\w.]+)"', text)}
    component_strings = {f"{p}/{a}" for p, a in components}
    packages = {p for p, _ in components}
    labels = set(re.findall(r'label="([^"]+)"', text))
    version = json.loads(VERSION_JSON.read_text(encoding="utf-8"))
    return {
        "components": component_strings,
        "packages": packages,
        "labels": {l.casefold() for l in labels},
        "pack_version": version.get("versionName", "?"),
    }


def status_of(component: str, pack: dict) -> str:
    if not component:
        return "NO-COMPONENT"
    if component in pack["components"]:
        return "EXACT"
    if component.split("/")[0] in pack["packages"]:
        return "PKG-ONLY"
    return "NOT-IN-PACK"


def mapped_of(package: str, name: str, pack: dict) -> str:
    if package and package in pack["packages"]:
        return "MAPPED"
    if name and name.casefold() in pack["labels"]:
        return "NAME-MATCH"
    return "NOT-MAPPED"


# ---------------------------------------------------------------------------
# The report
# ---------------------------------------------------------------------------

def render(issues: list[dict], pack: dict, generated: datetime) -> str:
    now = generated
    requests = [i for i in issues if is_icon_request(i)]
    not_applying = [i for i in issues if is_not_applying(i)]

    def split(lst):
        return [i for i in lst if i["state"] == "CLOSED"], \
               [i for i in lst if i["state"] == "OPEN"]

    req_closed, req_open = split(requests)
    na_closed, na_open = split(not_applying)

    req_times = [days_between(i["createdAt"], i["closedAt"]) for i in req_closed]
    na_times = [days_between(i["createdAt"], i["closedAt"]) for i in na_closed]
    first_issue = min((i for i in requests + not_applying),
                      key=lambda i: i["createdAt"], default=None)

    # Distinct apps reported, and how many are in the pack now. First issue
    # per name wins; requests precede not-applying, so the package comes from
    # the request's component/store link rather than a report's.
    distinct: dict[str, tuple[str, dict]] = {}
    for i in requests + not_applying:
        name = app_name_of(i)
        distinct.setdefault(name.casefold(), (name, i))
    mapped_names = sum(1 for name, issue in distinct.values()
                       if mapped_of(package_of(issue), name, pack) == "MAPPED")

    lines = []
    add = lines.append
    add(f"<!-- {HEADER_MARKER} from the GitHub issue tracker and the bundled")
    add("     appfilter. Do not edit by hand: run `python tools/coverage_report.py")
    add("     --write` (the weekly refresh does this) - the CI gate fails if")
    add("     this file is missing or stale. -->")
    add("")
    add("# Coverage and mapping reliability")
    add("")
    add(f"Generated: {now:%Y-%m-%d} · pack v{pack['pack_version']} · "
        f"tracker live since {first_issue['createdAt'][:10] if first_issue else 'n/a'}")
    add("")
    add("## Headline")
    add("")
    add(f"- **{len(distinct)}** distinct apps reported since the tracker went "
        f"live; **{mapped_names}** are in the pack now")
    na_exact = sum(1 for i in na_closed if status_of(component_of(i), pack) == "EXACT")
    add(f"- **{na_exact}/{len(na_closed)}** closed not-applying reports have the "
        f"**exact reported component** shipped now (first-fix rate)")
    add(f"- Median resolution: **{median(req_times):.1f} days** on icon requests, "
        f"**{median(na_times):.1f} days** on not-applying "
        f"(worst {max(req_times, default=0):.1f} days)")
    add(f"- Open backlog: **{len(req_open)}** requests, **{len(na_open)}** "
        f"not-applying")
    add("")

    add("## Icon requests")
    add("")
    req_status = {}
    for i in req_closed:
        req_status[mapped_of(package_of(i), app_name_of(i), pack)] = \
            req_status.get(mapped_of(package_of(i), app_name_of(i), pack), 0) + 1
    add("| Closed | Count |")
    add("| --- | --- |")
    for status in ("MAPPED", "NAME-MATCH", "NOT-MAPPED"):
        if req_status.get(status):
            add(f"| {status} | {req_status[status]} |")
    add("")
    add("A request counts as MAPPED only when its package (from the component, "
        "or a Play store link's `id=`) is in the bundled appfilter; a label "
        "hit is reported as NAME-MATCH and never counted.")
    add("")

    add("## Mapping reliability — not applying")
    add("")
    add("| # | App | Reported component | Status now | Days |")
    add("| --- | --- | --- | --- | --- |")
    for i in sorted(na_closed, key=lambda x: x["number"]):
        comp = component_of(i)
        add(f"| [{i['number']}](https://github.com/{REPO_OWNER}/{REPO_NAME}/issues/"
            f"{i['number']}) | {app_name_of(i)} | `{comp}` | "
            f"{status_of(comp, pack)} | {days_between(i['createdAt'], i['closedAt']):.1f} |")
    add("")
    by_launcher: dict[str, list[dict]] = {}
    for i in na_closed:
        by_launcher.setdefault(launcher_of(i), []).append(i)
    add("By launcher (the form's Launcher field, device-line fallback):")
    add("")
    add("| Launcher | Closed | Exact component fixed |")
    add("| --- | --- | --- |")
    for launcher in sorted(by_launcher):
        rows = by_launcher[launcher]
        exact = sum(1 for i in rows
                    if status_of(component_of(i), pack) == "EXACT")
        add(f"| {launcher} | {len(rows)} | {exact} |")
    add("")

    add("## Open backlog")
    add("")
    open_all = sorted(req_open + na_open, key=lambda x: x["createdAt"])
    if open_all:
        add("| # | App | Kind | Age (days) | Component |")
        add("| --- | --- | --- | --- | --- |")
        for i in open_all:
            comp = component_of(i)
            kind = "request" if is_icon_request(i) else "not applying"
            age = (now - datetime.fromisoformat(
                i["createdAt"].replace("Z", "+00:00"))).days
            add(f"| [{i['number']}](https://github.com/{REPO_OWNER}/{REPO_NAME}/"
                f"issues/{i['number']}) | {app_name_of(i)} | {kind} | {age} | "
                f"`{comp}` |")
    else:
        add("Empty - nothing waiting.")
    add("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Entry points
# ---------------------------------------------------------------------------

def main(argv: list[str]) -> int:
    if "--check" in argv:
        if not REPORT.exists():
            print(f"{REPORT.relative_to(ROOT)} is missing - run "
                  "`python tools/coverage_report.py --write`")
            return 1
        text = REPORT.read_text(encoding="utf-8")
        if HEADER_MARKER not in text:
            print(f"{REPORT.relative_to(ROOT)} lost its generator header")
            return 1
        m = re.search(r"^Generated: (\d{4}-\d{2}-\d{2})", text, re.M)
        if not m:
            print("the report has no parseable Generated date")
            return 1
        generated = datetime.strptime(m.group(1), "%Y-%m-%d").replace(
            tzinfo=timezone.utc)
        age_days = (datetime.now(timezone.utc) - generated).days
        if age_days > STALE_AFTER_DAYS:
            print(f"the report is {age_days} days old "
                  f"(stale after {STALE_AFTER_DAYS}) - the weekly refresh "
                  "has lapsed")
            return 1
        print(f"coverage report ok - generated {m.group(1)}, {age_days} day(s) old")
        return 0

    issues = fetch_issues()
    pack = load_pack()
    generated = datetime.now(timezone.utc)
    text = render(issues, pack, generated)
    if "--write" in argv:
        REPORT.write_text(text, encoding="utf-8")
        print(f"wrote {REPORT.relative_to(ROOT)} "
              f"({len(issues)} issues, pack v{pack['pack_version']})")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
