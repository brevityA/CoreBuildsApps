def track_polyline(view: dict, points: int = 26) -> list[list[float]]:
    """The camera track, normalised into a 0..1 box, aspect preserved.

    Empty for anything the renderer cannot fly — the archive view has no
    coordinates and no camera. A decorative line invented for it would be a
    small lie in a mockup whose whole job is to be straight about art.
    """
    if not view.get("coordinates") or view.get("lane") != "render":
        return []
    camera = view.get("camera") or {}
    move = camera.get("move", "orbit")
    start = float(camera.get("startHeightM") or 500)
    end = float(camera.get("endHeightM") or start)
    pitch = float(camera.get("pitch") or renderer.DEFAULT_PITCH.get(move, 55))
    duration = float(view["durationSeconds"])

    raw = []
    for i in range(points):
        t = duration * i / max(1, points - 1)
        cam = views_geo.camera_at(view, move, t, duration, start, end, pitch)
        raw.append(cam["center"])

    lat0 = view["coordinates"][0]
    cos = abs(__import__("math").cos(__import__("math").radians(lat0))) or 1.0
    xs = [lon * cos for lon, _ in raw]
    ys = [lat for _, lat in raw]
    span = max(max(xs) - min(xs), max(ys) - min(ys), 1e-6)
    midx, midy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    return [[round(0.5 + (x - midx) / span, 3), round(0.5 - (y - midy) / span, 3)]
            for x, y in zip(xs, ys)]


def payload(view: dict) -> dict:
    camera = view.get("camera") or {}
    digest = hashlib.sha1(view["id"].encode()).hexdigest()
    return {
        "id": view["id"],
        "n": view["number"],
        "title": view["title"],
        "place": view["place"],
        "region": view["region"],
        "time": view["timeOfDay"],
        "scene": view["scene"],
        "lane": view["lane"],
        "move": camera.get("move", "—"),
        "duration": view["durationSeconds"],
        "fps": camera.get("fps") or 30,
        "accent": ACCENTS.get(view["scene"], "#00e5ff"),
        "tilt": int(digest[:2], 16) % 40 - 20,     # -20..19 degrees of wash
        "track": track_polyline(view),
        "captions": [[c["at"], c["text"]] for c in view.get("captions", [])],
        "credits": [c.get("source", "") for c in view.get("credits", [])],
        "renderable": view["lane"] == "render",
    }


def build() -> str:
    catalog = feeds.load_catalog()
    views = feeds.validate(catalog)
    rows = [payload(v) for v in sorted(views, key=lambda v: v["number"])]
    data = json.dumps({"views": rows}, ensure_ascii=False, separators=(",", ":"))
    return TEMPLATE.replace("/*__DATA__*/null", data)


