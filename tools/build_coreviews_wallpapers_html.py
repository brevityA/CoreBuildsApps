# The page's canvas is the loop's canvas: same 1.15 overscan, so the crop has
# the same room to drift. These are the exported pixels, not the TV's.
CANVAS_W = 1152
CANVAS_H = 648


def _hex(colour) -> str:
    r, g, b = (int(c) for c in colour)
    return f"#{r:02x}{g:02x}{b:02x}"


def canvas_data(clip, width: int, quality: int) -> dict:
    """Everything the page needs for one view, with its canvas embedded."""
    base = loops.base_texture(clip)
    height = round(width * canvas_height_ratio())
    small = base.resize((width, height), Image.LANCZOS)
    buffer = io.BytesIO()
    small.save(buffer, format="JPEG", quality=quality, optimize=True, progressive=True)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")

    track = loops.track_pixels(clip) if clip.move != "archive-timelapse" else []
    return {
        "id": clip.id,
        "title": clip.title,
        "place": clip.place,
        "region": clip.region,
        "scene": clip.scene,
        "move": clip.move,
        "accent": _hex(loops.accent_of(clip)),
        "captions": [[at, text] for at, text in clip.captions],
        # Normalised to the canvas, so the page can size it to whatever stage
        # it is drawn on without knowing the exported pixels.
        "track": [[round(x / loops.CW, 5), round(y / loops.CH, 5)] for x, y in track],
        "art": "data:image/jpeg;base64," + encoded,
    }


def canvas_height_ratio() -> float:
    return loops.CH / loops.CW


def build(width: int = CANVAS_W, quality: int = 80) -> str:
    views = [canvas_data(clip, width, quality) for clip in CLIPS]
    data = json.dumps({
        "title": "Core Views — live wallpapers",
        "drift": loops.DRIFT,
        "trail": loops.TRAIL,
        "views": views,
    }, ensure_ascii=False, separators=(",", ":"))
    return TEMPLATE.replace("/*__DATA__*/null", data)


