#!/usr/bin/env python3
"""Build one self-contained HTML page that plays the Core Views wallpapers.

`docs/core-views-wallpapers-preview.html` is the season as an example you can
open and watch: a 16:9 TV stage, the twelve loops, and the launcher chrome they
play under. Unlike the MP4s it is not a video — each view's canvas is embedded
as a base64 JPEG and the motion (the parallax crop, the light travelling the
camera's track) is drawn live in the page, from the same data the renderer
uses. No network, no codecs, no ffmpeg: one file, and it moves.

It is the same drawing as `tools/build_coreviews_loops.py`, at page scale:

  * the crop drifts on two whole cycles, so it loops without a seam;
  * the light runs the camera's track once, fading in at the start and out at
    the end, because a track is not a closed curve;
  * the archive view has no track, so it gets the terminator sweep instead.

    python tools/build_coreviews_wallpapers_html.py            # write
    python tools/build_coreviews_wallpapers_html.py --check    # CI
    python tools/build_coreviews_wallpapers_html.py --width 960 --quality 72

The stage is a **mockup of the app**, and the footer says what the art is: a
wallpaper drawn from each view's plan, not footage of the place.
"""
